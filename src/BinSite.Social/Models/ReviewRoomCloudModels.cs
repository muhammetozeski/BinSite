using System.Text.Json;
namespace BinSite.Social.Models;
/// <summary>Metadata for a real account-authorized cloud workspace.</summary>
public sealed record ReviewCloudItem(string Id,string Title,string Kind,int Revision,long UpdatedAt,string Role);
/// <summary>The server's shared quota summary, not a client-computed entitlement.</summary>
public sealed record ReviewCloudAccount(bool Premium,int ProjectLimit,int UsedProjects);
/// <summary>Lists actual authorized workspaces and the server's quota.</summary>
public sealed record ReviewCloudList(List<ReviewCloudItem> Workspaces,ReviewCloudAccount? Account);
/// <summary>A full role-authorized workspace whose body contains metadata and notes only.</summary>
public sealed record ReviewCloudWorkspace(string Id,string Title,string Kind,JsonElement Body,int Revision,string Role,long UpdatedAt);
/// <summary>The create, read or update response from the workspace API.</summary>
public sealed record ReviewCloudEnvelope(ReviewCloudWorkspace Workspace);
/// <summary>A real workspace invitation token generated by the server.</summary>
public sealed record ReviewCloudInvite(string Token,long ExpiresAt);
/// <summary>The workspace and role granted after an authenticated invitation acceptance.</summary>
public sealed record ReviewCloudJoin(string WorkspaceId,string Role);
